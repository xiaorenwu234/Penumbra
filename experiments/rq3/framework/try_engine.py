#!/usr/bin/env python3
"""try (OSDI'26) epoch engine for the RQ3 baseline experiment.

Implements the same epoch lifecycle the Penumbra orchestrator provides
(begin_epoch -> session_run -> commit/rollback) on top of `try`, the
effect-control tool from the OSDI'26 paper "Controlling Opaque-Component
Effects with Semisolates and Try" (source: <RQ2>/try-osdi26-ae).

Phase mapping (Penumbra -> try):
  begin_epoch   -> create a fresh sandbox directory (the `try -D` work root)
  session_run   -> `try -D <sandbox> -- <cmd>`: try provisions an overlay
                   sandbox (per top-level dir, inside a user namespace) and
                   runs the command in its chroot view; all file effects
                   land in the sandbox upperdir, the live tree is untouched
  commit        -> `try commit <sandbox>`: apply upperdir effects in place
                   onto the live tree, then drop the sandbox
  rollback      -> drop the sandbox; try's abort path performs no
                   restoration work (that is the point of the design)

Compared with the OverlayCriuEngine fallback baseline:
  - File effects: both sit on overlayfs; CRIU mounts one lower/upper pair
    itself, try mounts per-top-level-dir overlays via its native flow.
  - Process state: try has no process snapshot (its scope is file effects
    only), so there is no sleeper/CRIU phase and rollback restores no
    process state.
  - Cost attribution: try exposes no separate "prepare" phase — the
    sandbox provisioning (measured ~130 ms/epoch) is folded into the
    first command call, so run_ns carries it while begin_ns counts only
    the sandbox directory creation. total_ns is unaffected.

Measured pitfalls (keep these workarounds):
  - `try commit` MUST get an absolute sandbox path: upstream
    try-commit(C) walks the upperdir with fts, which chdir()s, so a
    relative sandbox path makes the rename() src resolve against the
    wrong cwd and fail with ENOENT ("couldn't commit ... (rename)").
  - `try`'s commit exit status is unreliable (upstream TRY_EXIT_STATUS is
    overwritten by the trace writer) -> the upperdir-drained check below
    is the authoritative success signal.
  - Running try AS ROOT breaks access to files owned by other uids:
    `unshare --map-root-user` then maps ONLY uid 0 ("0 0 1"), so the
    xht-owned RQ3 tree under /home/xht (home dir mode 0750, other has no
    search) turns into nobody-owned / unreachable inside the sandbox —
    every cd/exec of /home/xht/** fails with EACCES (command exit 126).
    Fix: a root-run unshare shim (installed by setup() into <root>/tools
    and prepended to PATH) drops the two userns flags — a real root needs
    no user namespace, mount isolation is already provided by try's mount
    namespace (verified: writes inside the sandbox still never reach the
    live tree).
  - try's overlay workdir contains a kernel-created 000-mode `work/`
    subdir; non-root teardown cannot recurse into it (leftovers under
    /tmp only — root runs remove everything).

Requires: Linux >= 5.11 (unshare + overlayfs inside a user namespace).
Does NOT require root, but the RQ3 harness runs everything as root for
consistency with the other experiments.
"""

import os
import shlex
import shutil
import stat
import subprocess
import tempfile
from typing import List, Optional

from .baseline_engine import BaselineEngineError
from .timing import Timer

# Directory names inside the engine root
DIR_WORK = "work"            # live work tree (the "lower" the workloads use)
DIR_SANDBOXES = "sandboxes"  # one fresh sandbox dir per epoch
DIR_TOOLS = "tools"          # root-run shim dir (unshare wrapper)

# Root-run unshare shim installed by setup() into <root>/tools/unshare and
# prepended to the try subprocess PATH. See the module docstring's pitfalls:
# try's fixed `unshare --mount --map-root-user --user --pid --fork` maps
# ONLY uid 0 when try runs as real root, making other-uid files (the RQ3
# tree under /home/xht) unreachable inside the sandbox. A real root needs
# no user namespace (mount isolation comes from the mount namespace), so
# the shim drops the two userns flags and forwards everything else.
_ROOT_UNSHARE_SHIM = """#!/bin/bash
# Auto-generated by framework/try_engine.py — do not edit.
# Drops try's userns flags when running as real root (see TryEngine docs).
args=()
for a in "$@"; do
    case "$a" in
        --map-root-user|--user) ;;
        *) args+=("$a") ;;
    esac
done
exec {real_unshare} "${{args[@]}}"
"""

_HERE = os.path.dirname(os.path.abspath(__file__))
_RQ3_DIR = os.path.dirname(_HERE)
_RQ2_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(_RQ3_DIR)))


# ─── Locating the try installation (unit-testable without root) ──────────────

def try_root_candidates() -> List[str]:
    """Where to look for the try source tree, in priority order."""
    cands = []
    env_src = os.environ.get("TRY_SRC")
    if env_src:
        cands.append(env_src)
    cands.append(os.path.join(_RQ2_ROOT, "try-osdi26-ae"))
    cands.append(os.path.join(_RQ3_DIR, "third_party", "try-osdi26-ae"))
    return cands


def find_try_binary() -> Optional[str]:
    """Locate the try executable.

    Search order: $TRY_BIN -> <RQ2>/try-osdi26-ae/try ->
    <rq3>/third_party/try-osdi26-ae/try -> $PATH. Returns None when not
    found (build it with: bash third_party/build_try.sh).
    """
    env_bin = os.environ.get("TRY_BIN")
    if env_bin:
        return env_bin if (os.path.isfile(env_bin)
                           and os.access(env_bin, os.X_OK)) else None
    for root in try_root_candidates():
        cand = os.path.join(root, "try")
        if os.path.isfile(cand) and os.access(cand, os.X_OK):
            return cand
    return shutil.which("try")


def find_try_utils_dir(try_bin: Optional[str]) -> Optional[str]:
    """Locate the directory holding try-commit / try-summary.

    $TRY_UTILS_DIR -> <try_root>/utils (source layout) -> <try_bin dir>
    (the install layout puts try and the utilities side by side in
    $bindir). Both binaries must be executable. None means try will fall
    back to its pure-shell commit path — correct but an order of
    magnitude slower per commit, so performance runs need the C tools.
    """
    def _has_utils(d: str) -> bool:
        return all(
            os.path.isfile(os.path.join(d, name))
            and os.access(os.path.join(d, name), os.X_OK)
            for name in ("try-commit", "try-summary"))

    env_dir = os.environ.get("TRY_UTILS_DIR")
    if env_dir and _has_utils(env_dir):
        return env_dir
    if try_bin:
        bin_dir = os.path.dirname(os.path.abspath(try_bin))
        for cand in (os.path.join(bin_dir, "utils"), bin_dir):
            if _has_utils(cand):
                return cand
    return None


def build_try_command(argv: List[str]) -> str:
    """Flatten a command argv into try's single-argument command string.

    try writes "$@" verbatim into script_to_execute.sh and *sources* it,
    so the command must arrive as one shell-quoted argument: passing
    ["bash", "-c", "echo a"] as separate argv entries would make try echo
    them space-joined ("bash -c echo a") and the inner quoting context is
    lost (documented try quoting behaviour). shlex.quote per element keeps
    the source step faithful for any argv the harness builds.
    """
    return " ".join(shlex.quote(a) for a in argv)


def is_overlay_whiteout(path: str) -> bool:
    """True if `path` is an overlayfs whiteout (a deletion marker).

    try's overlays are mounted with userxattr, but this kernel family
    materializes whiteouts as char-device (0,0) entries; other kernels
    use a regular file carrying the user.overlay.whiteout xattr, so both
    forms are recognized. Whiteouts are EXPECTED leftovers after a
    successful commit: applying a deletion to the live tree is the
    effect, and the marker stays behind in the sandbox (by design).
    """
    try:
        st = os.lstat(path)
    except OSError:
        return False
    if stat.S_ISCHR(st.st_mode) and st.st_rdev == 0:
        return True
    if stat.S_ISREG(st.st_mode):
        try:
            os.getxattr(path, "user.overlay.whiteout")
            return True
        except OSError:
            pass
    return False


# ─── Engine ──────────────────────────────────────────────────────────────────

class TryEngine:
    """One isolated session backed by the `try` sandbox lifecycle.

    Lifecycle:
        setup()                    create the directory tree
        session_open()/close()     no-ops (try has no persistent session)
        timed_begin_epoch()        create a fresh sandbox dir        [timed]
        timed_run(...)             try -D <sandbox> -- cmd           [timed]
        timed_commit()             try commit <sandbox> + discard    [timed]
        timed_rollback()           discard the sandbox               [timed]
        recover_failed_epoch()     untimed discard after a failure
        refresh()                  no-op (a fresh sandbox sees the live
                                   tree by construction)
        teardown()                 remove the whole directory tree
    """

    # The shared BaselineHarness merges a multi-command epoch into ONE
    # engine call when this is set: try's sandbox provisioning is per-call
    # (~130 ms), so calling it once per command would multiply a fixed
    # cost the Penumbra epoch pays only once. (Single-command epochs are
    # unaffected either way.)
    merge_epoch_commands = True

    # Reported in result params / comparison tables.
    engine_name = "try"

    def __init__(self, root: str, verbose: bool = True,
                 try_bin: str = None):
        self.root = os.path.abspath(root)
        self.work = os.path.join(self.root, DIR_WORK)
        # try sandboxes the live filesystem itself: the backing store and
        # the merged view the workloads talk to are the same live path.
        self.lower = self.work
        self.mnt = self.work
        self.sandboxes = os.path.join(self.root, DIR_SANDBOXES)
        self.tools = os.path.join(self.root, DIR_TOOLS)
        self.verbose = verbose
        self.try_bin = try_bin or find_try_binary()
        if not self.try_bin:
            raise BaselineEngineError(
                "try binary not found (set TRY_BIN, or build it with: "
                "bash experiments/rq3/third_party/build_try.sh)")
        self.try_utils_dir = find_try_utils_dir(self.try_bin)
        # Interface compat with the shared BaselineHarness: try has no
        # process-state snapshot, so the session payload axis (W10) is a
        # no-op here — the value is accepted and ignored.
        self.sleeper_mem_bytes = 0
        self._sandbox: Optional[str] = None  # current epoch's sandbox dir

    def log(self, msg: str):
        if self.verbose:
            print(f"  [try] {msg}", flush=True)

    # ─── lifecycle ────────────────────────────────────────────────────────

    def setup(self):
        """Create the engine directory tree. Idempotent."""
        os.makedirs(self.work, exist_ok=True)
        os.makedirs(self.sandboxes, exist_ok=True)
        if os.geteuid() == 0:
            self._install_root_unshare_shim()
        if not self.try_utils_dir:
            self.log("warning: try-commit/try-summary not found — try will "
                     "use its slow shell commit path (rebuild with "
                     "third_party/build_try.sh for the C fast path)")

    def _install_root_unshare_shim(self):
        """Install the root-run unshare wrapper into <root>/tools.

        See _ROOT_UNSHARE_SHIM and the module docstring: as real root,
        try's --map-root-user maps only uid 0 and other-uid files become
        unreachable inside the sandbox (EACCES / exit 126). The shim is
        prepended to PATH by _try_env() and only affects try subprocesses.
        """
        real = shutil.which("unshare")
        if not real:
            raise BaselineEngineError(
                "unshare not found (required to run try)")
        os.makedirs(self.tools, exist_ok=True)
        shim = os.path.join(self.tools, "unshare")
        with open(shim, "w") as f:
            f.write(_ROOT_UNSHARE_SHIM.format(real_unshare=real))
        os.chmod(shim, 0o755)

    def teardown(self):
        """Remove the engine directory tree entirely."""
        self.session_close()
        shutil.rmtree(self.root, ignore_errors=True)

    def session_open(self):
        """try has no persistent session — deliberately a no-op."""

    def session_close(self):
        """try has no persistent session — deliberately a no-op."""

    def refresh(self):
        """No-op: every epoch mounts a brand-new sandbox whose lowerdir is
        the live tree, so setup_fn() writes are visible by construction
        (the overlayfs+CRIU engine had to rebuild its mount for this)."""

    # ─── sandbox plumbing ─────────────────────────────────────────────────

    def _try_env(self) -> dict:
        env = dict(os.environ)
        path_dirs = []
        if os.geteuid() == 0 and os.path.isdir(self.tools):
            # unshare shim first: it must shadow /usr/bin/unshare for the
            # try script's `unshare ...` invocations (root runs only).
            path_dirs.append(self.tools)
        if self.try_utils_dir:
            path_dirs.append(self.try_utils_dir)
        if path_dirs:
            env["PATH"] = os.pathsep.join(path_dirs + [env.get("PATH", "")])
        # Pin the shell try runs the command with (set_TRY_SHELL honours an
        # existing executable $TRY_SHELL): deterministic bash semantics
        # regardless of the experiment launcher's $SHELL.
        env.setdefault("TRY_SHELL", "/bin/bash")
        return env

    def _discard_sandbox(self):
        """Drop the current sandbox.

        try's abort needs no restoration — not committing leaves the live
        tree untouched; deleting the sandbox dir is our own bookkeeping
        (one fresh sandbox per epoch). The kernel creates a 000-mode
        work/ subdir inside try's overlay workdir, so a plain rmtree can
        leave stubs behind for non-root users; the chmod pass below opens
        them up and retries (root runs never hit that branch; either way
        it is untimed bookkeeping).
        """
        if not (self._sandbox and os.path.isdir(self._sandbox)):
            self._sandbox = None
            return
        path = self._sandbox
        self._sandbox = None
        shutil.rmtree(path, ignore_errors=True)
        if os.path.isdir(path):
            for dirpath, dirnames, _filenames in os.walk(path, topdown=True):
                for name in dirnames:
                    try:
                        os.chmod(os.path.join(dirpath, name), 0o700)
                    except OSError:
                        pass
            shutil.rmtree(path, ignore_errors=True)

    def _run(self, argv: List[str],
             timeout: float) -> subprocess.CompletedProcess:
        return subprocess.run(argv, cwd=self.mnt, capture_output=True,
                              text=True, timeout=timeout, env=self._try_env())

    def _upperdir_remaining(self) -> List[str]:
        """Non-directory, non-whiteout entries still in the sandbox upper.

        try-commit applies effects by *moving* upper entries onto the live
        tree; anything left over (files/symlinks) means some effect was
        NOT applied. Two kinds of expected leftovers are excluded:
        directory skeletons (try pre-creates one per top-level mountpoint)
        and whiteouts (a committed deletion legitimately leaves its
        deletion marker behind — the live file is already gone).
        """
        leftover = []
        upper = os.path.join(self._sandbox, "upperdir")
        for dirpath, _dirs, files in os.walk(upper):
            for name in files:
                path = os.path.join(dirpath, name)
                if is_overlay_whiteout(path):
                    continue
                leftover.append(path)
        return leftover

    # ─── epoch phases ─────────────────────────────────────────────────────

    def timed_begin_epoch(self) -> int:
        """Create a fresh sandbox directory. Returns elapsed ns.

        A fresh sandbox per epoch is what makes rollback semantics exact:
        the sandbox lowerdir is the live tree (as of sandbox creation) and
        the upperdir starts empty, so an uncommitted epoch leaves the live
        filesystem byte-identical.
        """
        self._discard_sandbox()
        with Timer() as t:
            self._sandbox = tempfile.mkdtemp(prefix="epoch-",
                                             dir=self.sandboxes)
        return t.elapsed_ns

    def timed_run(self, argv: List[str], timeout: float = 60.0):
        """Run one command inside the epoch's try sandbox.

        Returns (returncode, output, elapsed_ns) with output = stdout +
        stderr merged (same contract as OverlayCriuEngine.timed_run:
        Penumbra's session log captures both streams, so verify_fn
        regexes run against the combined text — W10 prints its metadata
        to stderr).

        `-D` implies quiet mode (no prompt, no commit) and REUSES the same
        sandbox dir across the epoch's calls, so a multi-command epoch
        accumulates every command's effects into one sandbox that one
        later `try commit` applies atomically. Each -D call still
        re-provisions the sandbox (unshare+mounts), which is where try's
        per-call fixed cost lives.
        """
        if self._sandbox is None:
            raise BaselineEngineError(
                "timed_run called without timed_begin_epoch")
        cmd = build_try_command(argv)
        full = [self.try_bin, "-D", self._sandbox, "--", cmd]
        with Timer() as t:
            try:
                proc = self._run(full, timeout)
                rc = proc.returncode
                out = (proc.stdout or "") + (proc.stderr or "")
            except subprocess.TimeoutExpired:
                rc, out = 124, ""
        return rc, out, t.elapsed_ns

    def timed_commit(self) -> int:
        """Apply the sandbox effects to the live tree, then drop the
        sandbox. Returns elapsed ns.

        Correctness guard: upstream try's commit exit status is
        unreliable (TRY_EXIT_STATUS is overwritten by the trace writer),
        so the upperdir-drained check is the authoritative signal. The
        sandbox path MUST stay absolute — try-commit(C) walks the upperdir
        via fts, which chdir()s, and a relative path makes its rename()
        src resolve against the wrong cwd (ENOENT, measured).
        """
        if self._sandbox is None:
            raise BaselineEngineError(
                "timed_commit called without timed_begin_epoch")
        with Timer() as t:
            proc = self._run([self.try_bin, "commit", self._sandbox],
                             timeout=120.0)
            leftover = self._upperdir_remaining()
            self._discard_sandbox()
        if proc.returncode != 0 or leftover:
            raise BaselineEngineError(
                f"try commit failed (rc={proc.returncode}, "
                f"{len(leftover)} uncommitted entries; stderr: "
                f"{(proc.stderr or '').strip()[-200:]!r})")
        return t.elapsed_ns

    def timed_rollback(self) -> int:
        """Discard the speculative sandbox. Returns elapsed ns.

        try's abort path performs no restoration work — dropping the
        sandbox *is* the rollback (cf. the CRIU engine's restore+reset;
        both finalize phases include dropping the speculative state, so
        the accounting is symmetric).
        """
        with Timer() as t:
            self._discard_sandbox()
        return t.elapsed_ns

    def recover_failed_epoch(self):
        """Untimed recovery after a failed run phase: drop the sandbox."""
        try:
            self._discard_sandbox()
        except OSError as e:
            self.log(f"recovery failed: {e}")


# ─── Smoke test (usable without root) ────────────────────────────────────────

def smoke_test(root: str, verbose: bool = True) -> bool:
    """One full engine cycle with hard verifications — validates the
    sandbox lifecycle (create/run/isolate/commit/discard/delete-effect)
    before any real measurement. Returns success."""
    print("=" * 62)
    print("  TRY ENGINE SMOKE TEST (OSDI'26 try)")
    print("=" * 62)
    ok = True
    engine = TryEngine(root, verbose=True)
    engine.setup()
    wd = os.path.join(engine.work, "rq3-work")
    os.makedirs(wd, exist_ok=True)

    def check(name, cond, detail=""):
        nonlocal ok
        status = "PASS" if cond else "FAIL"
        if not cond:
            ok = False
        print(f"  [{status}] {name}" + (f" — {detail}" if detail else ""))

    def run_writes(rel_abs, content):
        # Absolute paths inside the sandbox-view tree, mirroring how the
        # real workloads address files (spec_command uses mnt_work_path).
        rc, out, ns = engine.timed_run(
            ["bash", "-c", f"printf '%s' '{content}' > {rel_abs}"])
        return rc, out, ns

    try:
        engine.session_open()

        # ── 1. isolation: an uncommitted write must not touch the live tree ──
        f_new = os.path.join(wd, "newfile.txt")
        engine.timed_begin_epoch()
        rc, out, ns = run_writes(f_new, "spec")
        check("run in sandbox", rc == 0, f"rc={rc} {ns/1e6:.1f} ms")
        check("live tree isolated", not os.path.exists(f_new))
        engine.timed_rollback()
        check("rollback keeps live tree clean", not os.path.exists(f_new))

        # ── 2. commit: the effect must land in the live tree ──
        f_com = os.path.join(wd, "committed.txt")
        engine.timed_begin_epoch()
        rc, _, ns = run_writes(f_com, "kept")
        if rc != 0:
            check("commit run", False, f"rc={rc}")
            return ok
        ns = engine.timed_commit()
        content = open(f_com).read() if os.path.exists(f_com) else ""
        check("commit applies effect to live tree",
              content == "kept", f"{ns/1e6:.1f} ms")

        # ── 3. rollback must not revert already-committed state ──
        engine.timed_begin_epoch()
        run_writes(f_com, "spec-overwrite")
        engine.timed_rollback()
        content = open(f_com).read()
        check("rollback preserves committed content", content == "kept")

        # ── 4. delete-effect propagates on commit (whiteout path) ──
        engine.timed_begin_epoch()
        rc, _, _ = engine.timed_run(["bash", "-c", f"rm {f_com}"])
        check("rm inside sandbox", rc == 0, f"rc={rc}")
        check("live file still present before commit", os.path.exists(f_com))
        engine.timed_commit()
        check("commit propagates deletion", not os.path.exists(f_com))

        # ── 5. sandbox cleanup: no sandbox dirs left, engine reusable ──
        leftovers = (os.listdir(engine.sandboxes)
                     if os.path.isdir(engine.sandboxes) else [])
        check("sandbox dirs cleaned up", leftovers == [],
              f"{len(leftovers)} left")
    finally:
        engine.session_close()
        engine.teardown()

    print("=" * 62)
    print(f"  SMOKE TEST {'PASSED' if ok else 'FAILED'}")
    print("=" * 62)
    return ok


if __name__ == "__main__":
    import sys
    _root = tempfile.mkdtemp(prefix="rq3-try-smoke-")
    sys.exit(0 if smoke_test(_root) else 1)
